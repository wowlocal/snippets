import Foundation

// Shared helpers for the generator. Strings are handled as arrays of Unicode scalar
// values so that nothing here depends on how a source file or a terminal spells them.

typealias Scalars = [UInt32]

/// Every Unicode scalar value, in order (surrogates are not scalars).
let allScalars: Scalars = {
    var values: Scalars = []
    values.reserveCapacity(0x110000 - 0x800)
    for value in UInt32(0)...0x10FFFF where !(0xD800...0xDFFF).contains(value) {
        values.append(value)
    }
    return values
}()

@inline(__always)
func makeString(_ values: Scalars) -> String {
    var view = String.UnicodeScalarView()
    view.reserveCapacity(values.count)
    for value in values { view.append(Unicode.Scalar(value)!) }
    return String(view)
}

@inline(__always)
func scalarValues(_ text: String) -> Scalars {
    text.unicodeScalars.map { $0.value }
}

func hex(_ value: UInt32) -> String {
    let digits = String(value, radix: 16, uppercase: true)
    return digits.count >= 4 ? digits : String(repeating: "0", count: 4 - digits.count) + digits
}

/// Space-separated scalar values; `-` for the empty string, so a field is never empty.
func hex(_ values: Scalars) -> String {
    values.isEmpty ? "-" : values.map { hex($0) }.joined(separator: " ")
}

func hex(_ text: String) -> String { hex(scalarValues(text)) }

/// xorshift64: the output files must not change between two runs on the same system.
struct SeededRandom {
    private var state: UInt64

    init(seed: UInt64) { state = seed == 0 ? 0x9E37_79B9_7F4A_7C15 : seed }

    mutating func next() -> UInt64 {
        state ^= state << 13
        state ^= state >> 7
        state ^= state << 17
        return state
    }

    mutating func int(_ upperBound: Int) -> Int {
        upperBound <= 0 ? 0 : Int(next() % UInt64(upperBound))
    }

    mutating func bool() -> Bool { next() & 1 == 0 }

    mutating func pick<T>(_ options: [T]) -> T { options[int(options.count)] }
}

/// `start-end` (or `start`) lines for the scalars whose value under `key` is not `skip`.
func rangeLines<Key: Equatable>(skip: Key, key: (UInt32) -> Key, format: (Key) -> String) -> [String] {
    var lines: [String] = []
    var start: UInt32 = 0
    var previous: UInt32 = 0
    var current: Key? = nil

    func flush() {
        guard let current, current != skip else { return }
        let range = start == previous ? hex(start) : "\(hex(start))-\(hex(previous))"
        let suffix = format(current)
        lines.append(suffix.isEmpty ? range : "\(range) \(suffix)")
    }

    for value in allScalars {
        let next = key(value)
        // A run never continues across the surrogate gap.
        if let existing = current, existing == next, value == previous + 1 {
            previous = value
            continue
        }
        flush()
        current = next
        start = value
        previous = value
    }
    flush()
    return lines
}

struct GeneratorEnvironment {
    let macOS: String
    let swift: String

    func header(_ title: String, _ notes: [String] = []) -> [String] {
        var lines = [
            "# \(title)",
            "# Generated by snippets-android/tools/foundation-tables/regenerate.sh. Do not edit.",
            "# macOS: \(macOS)",
            "# Swift: \(swift)",
        ]
        lines += notes.map { "# \($0)" }
        return lines
    }
}

func write(_ lines: [String], to url: URL) {
    let text = lines.joined(separator: "\n") + "\n"
    do {
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url, options: .atomic)
    } catch {
        fatalError("could not write \(url.path): \(error)")
    }
    print("wrote \(url.lastPathComponent): \(lines.count) lines")
}

func require(_ condition: @autoclosure () -> Bool, _ message: @autoclosure () -> String) {
    if !condition() {
        FileHandle.standardError.write(Data("generator check failed: \(message())\n".utf8))
        exit(1)
    }
}
