#!/usr/bin/env python3
"""Generates each CLI's copy of the agent skill text from `agent-skill/`.

`agent-skill/guide.md` is the one source for both platforms. Lines between
`<!-- mac -->` and `<!-- /mac -->` (or the `linux` pair) belong to that platform
only. This writes:

  snippets/Core/AgentSkillText.swift        macOS guide, default rules, stub
  snippets-linux/src/agent_skill/*.md       Linux guide, default rules, stub

Run it after changing anything in `agent-skill/`. `--check` fails if a generated
file is stale, without writing anything.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "agent-skill"
SWIFT = ROOT / "snippets/Core/AgentSkillText.swift"
LINUX = ROOT / "snippets-linux/src/agent_skill"
PLATFORMS = ("mac", "linux")
MARKER = re.compile(r"^<!-- (/?)(mac|linux) -->$")


def for_platform(text: str, platform: str) -> str:
    lines, inside = [], None
    for number, line in enumerate(text.splitlines(), 1):
        match = MARKER.match(line.strip())
        if match:
            closing, name = match.group(1) == "/", match.group(2)
            if closing != (inside is not None) or (closing and name != inside):
                sys.exit(f"guide.md:{number}: unbalanced platform marker")
            inside = None if closing else name
            continue
        if inside is None or inside == platform:
            lines.append(line)
    if inside is not None:
        sys.exit("guide.md: unclosed platform marker")
    text = "\n".join(lines).strip() + "\n"
    return re.sub(r"\n{3,}", "\n\n", text)


def swift_literal(text: str) -> str:
    if '"""#' in text:
        sys.exit("text contains a raw-string terminator")
    return '#"""\n' + text + '"""#'


def outputs() -> dict:
    guide = (SOURCE / "guide.md").read_text()
    rules = (SOURCE / "rules.md").read_text()
    stub = (SOURCE / "stub.md").read_text()
    swift = (
        "// Generated by scripts/agent-skill.py from agent-skill/. Do not edit.\n\n"
        "nonisolated enum AgentSkillText {\n"
        f"    static let guide = {swift_literal(for_platform(guide, 'mac'))}\n\n"
        f"    static let defaultRules = {swift_literal(rules)}\n\n"
        f"    static let stubTemplate = {swift_literal(stub)}\n"
        "}\n"
    )
    return {
        SWIFT: swift,
        LINUX / "guide.md": for_platform(guide, "linux"),
        LINUX / "rules.md": rules,
        LINUX / "stub.md": stub,
    }


def main() -> None:
    check = sys.argv[1:] == ["--check"]
    stale = []
    for path, text in outputs().items():
        current = path.read_text() if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and stale:
        sys.exit("stale, run scripts/agent-skill.py: " + ", ".join(map(str, stale)))
    for path in stale:
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
